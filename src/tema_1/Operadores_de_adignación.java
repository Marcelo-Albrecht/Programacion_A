package tema_1;

public class Operadores_de_adignación {
	public static void main(String[] args) {
	    int a = 10;
	    // Vamos a mostrar cada valor de en cada cambio
	    a += 5; // a ahora es 15
	    System.out.println("Nuevo valor de a : " + a);
	    a -= 3; // a ahora es 12
	    System.out.println("Nuevo valor de a: " + a);
	    a *= 2; // a ahora es 24
	    System.out.println("Nuevo valor de a: " + a);
	    a /= 4; // a ahora es 6
	    System.out.println("Nuevo valor de a: " + a);
	    a %= 5; // a ahora es 1
	    System.out.println("Nuevo valor de a: " + a);
	   
	}

}
