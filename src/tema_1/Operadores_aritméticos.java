package tema_1;

public class Operadores_aritméticos {
	public static void main(String[] args) {
	    int a = 10;
	    int b = 5;
	    // Creamos una variable por cada operación
	    int suma = a + b;
	    int resta = a - b;
	    int mult = a * b;
	    int divide = a / b;
	    int modulo = a % b;
	    // Mostramos por pantalla las diferentes operaciones
	    
		System.out.println("Suma: " + suma); // 15
		System.out.println("Resta: " + resta); // 5
		System.out.println("Multiplica: " + mult); // 50
		System.out.println("Divisíon: " + divide); // 2
		System.out.println("Módulo: " + modulo); // 0
	}

}
